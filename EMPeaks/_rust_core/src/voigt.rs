// ================================================================
// Voigt プロファイル（xsf::voigt_profile = scipy互換）
// voigt_profile(x, sigma, gamma) は規格化されていない (∫ = 1 over (-∞,∞))
// ================================================================

#[inline]
fn voigt_pdf(x: f64, x0: f64, sigma: f64, gamma: f64) -> f64 {
    xsf::voigt_profile(x - x0, sigma, gamma)
}

// ================================================================
// スマートCDF: 裾野引き算方式
// direction = -1: (-∞, limit] を積分
// direction = +1: [limit, ∞) を積分
// ================================================================

fn tail_integral(limit: f64, direction: f64, x0: f64, sigma: f64, gamma: f64) -> f64 {
    let mut sum = 0.0;
    for i in 0..N_QUAD {
        let u = QUAD_U[i];
        let w = QUAD_W[i];
        let t = limit + direction * (u / (1.0 - u));
        let jac = 1.0 / ((1.0 - u) * (1.0 - u));
        sum += w * voigt_pdf(t, x0, sigma, gamma) * jac;
    }
    sum
}

fn smart_cdf(x: f64, x0: f64, sigma: f64, gamma: f64) -> f64 {
    if x <= x0 {
        tail_integral(x, -1.0, x0, sigma, gamma)
    } else {
        1.0 - tail_integral(x, 1.0, x0, sigma, gamma)
    }
}

pub fn compute_z(x0: f64, sigma: f64, gamma: f64, x_min: f64, x_max: f64) -> f64 {
    smart_cdf(x_max, x0, sigma, gamma) - smart_cdf(x_min, x0, sigma, gamma)
}

// ================================================================
// predict / LL
// ================================================================

pub fn predict_inplace(
    x: &[f64], x0: f64, sigma: f64, gamma: f64,
    x_min: f64, x_max: f64, out: &mut [f64],
) {
    let z = compute_z(x0, sigma, gamma, x_min, x_max).max(1e-300);
    for i in 0..x.len() {
        out[i] = voigt_pdf(x[i], x0, sigma, gamma) / z;
    }
}

fn ll_voigt(
    x: &[f64], intensity: &[f64],
    x0: f64, sigma: f64, gamma: f64,
    x_min: f64, x_max: f64,
) -> f64 {
    let z = compute_z(x0, sigma, gamma, x_min, x_max).max(1e-300);
    x.iter().zip(intensity.iter())
        .map(|(&xi, &ii)| {
            let p = voigt_pdf(xi, x0, sigma, gamma) / z;
            ii * (p + 1e-200).ln()
        })
        .sum()
}

// ================================================================
// MLE（L-BFGS-B、fix_ フラグ対応）
// ================================================================

pub fn mle_voigt(
    x: &[f64], intensity: &[f64],
    x0: &mut f64, sigma: &mut f64, gamma: &mut f64,
    fix_x0: bool, fix_sigma: bool, fix_gamma: bool,
    x_min: f64, x_max: f64,
    sigma_min: f64, sigma_max: f64,
    gamma_min: f64, gamma_max: f64,
) {
    if fix_x0 && fix_sigma && fix_gamma {
        return;
    }
    if intensity.iter().sum::<f64>() == 0.0 {
        return;
    }

    let mut init = Vec::new();
    let mut bounds_lower = Vec::new();
    let mut bounds_upper = Vec::new();

    if !fix_x0    { init.push(*x0);    bounds_lower.push(x_min); bounds_upper.push(x_max); }
    if !fix_sigma { init.push(*sigma); bounds_lower.push(sigma_min); bounds_upper.push(sigma_max); }
    if !fix_gamma { init.push(*gamma); bounds_lower.push(gamma_min); bounds_upper.push(gamma_max); }

    let eps_num = 1e-7_f64;
    let x0_fixed = *x0;
    let sigma_fixed = *sigma;
    let gamma_fixed = *gamma;
    let x_s = x.to_vec();
    let w_s = intensity.to_vec();

    let unpack = move |p: &[f64]| -> (f64, f64, f64) {
        let mut idx = 0;
        let x0_v  = if fix_x0    { x0_fixed    } else { let v = p[idx]; idx += 1; v };
        let sig_v = if fix_sigma { sigma_fixed } else { let v = p[idx]; idx += 1; v };
        let gam_v = if fix_gamma { gamma_fixed } else { let v = p[idx]; idx += 1; v };
        (x0_v, sig_v, gam_v)
    };

    let mut solver = lbfgsb_rs_pure::LBFGSB::new(10)
        .with_max_iter(10000)
        .with_pgtol(1e-5);
    let mut f_and_grad = |p: &[f64]| -> (f64, Vec<f64>) {
        let (x0_v, sig_v, gam_v) = unpack(p);
        let ll = ll_voigt(&x_s, &w_s, x0_v, sig_v, gam_v, x_min, x_max);
        let mut g = vec![0.0; p.len()];

        for i in 0..p.len() {
            let mut p_eps = p.to_vec();
            p_eps[i] += eps_num;
            let (x0_e, sig_e, gam_e) = unpack(&p_eps);
            let ll_e = ll_voigt(&x_s, &w_s, x0_e, sig_e, gam_e, x_min, x_max);
            g[i] = -(ll_e - ll) / eps_num;
        }
        (-ll, g)
    };

    if let Ok(state) = solver.minimize(&mut init, &bounds_lower, &bounds_upper, &mut f_and_grad) {
        let (x0_r, sig_r, gam_r) = unpack(&state.x);
        if !fix_x0    { *x0    = x0_r; }
        if !fix_sigma { *sigma = sig_r.clamp(sigma_min, sigma_max); }
        if !fix_gamma { *gamma = gam_r.clamp(gamma_min, gamma_max); }
    }
}

// Voigt プロファイルの規格化定数なしの予測値（predict のみ公開）
pub fn predict(x: &[f64], x0: f64, sigma: f64, gamma: f64, x_min: f64, x_max: f64) -> Vec<f64> {
    let mut out = vec![0.0; x.len()];
    predict_inplace(x, x0, sigma, gamma, x_min, x_max, &mut out);
    out
}
